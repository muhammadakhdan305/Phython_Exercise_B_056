# List Hewan
Animals = ["Kucing", "Anjing", "Ikan"]
print("======================================================")
print()
# Loop Nama Hewan
for animal in Animals:
    print(animal)
print()
print("======================================================")
print()

# Loop Kalimat
for animal in Animals:
    print(f"Saya suka hewan {animal}.")
    print(f"{animal} adalah hewan yang lucu dan menggemaskan.")
    print("Hewan-Hewan ini sangat menyenangkan untuk dipelihara di rumah!")
    print()

print("=======================================================")
