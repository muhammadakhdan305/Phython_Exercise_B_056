# Deskripsi = Program ini berisi tentang penggunaan method lstrip(), rstrip(), dan strip() yang berfungsi untuk menghapus whitespace dari sebuah string.

name = "\t\n     TristanNaya     \n\t"

print("Original:")
print(name)

print("lstrip():")
print(name.lstrip())

print("rstrip():")
print(name.rstrip())  

print("strip():")
print(name.strip())